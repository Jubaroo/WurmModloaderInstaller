// Generates lang/strings.nsh from tools/lang/*.json
//
// Each JSON file: { "language": "LANG_GERMAN", "strings": { KEY: "text", ... } }
// Text uses \n for line breaks (written as $\r$\n) and must not contain
// double quotes or dollar signs other than ${DEFINES}.
//
// Usage: node tools/gen-lang.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const langDir = path.join(here, 'lang');
const outFile = path.join(here, '..', 'lang', 'strings.nsh');

const files = fs.readdirSync(langDir).filter(f => f.endsWith('.json')).sort();
if (files.length === 0) throw new Error('no language files found');

const langs = files.map(f => {
  const data = JSON.parse(fs.readFileSync(path.join(langDir, f), 'utf8'));
  if (!data.language || !data.strings) throw new Error(`${f}: missing language or strings`);
  return { file: f, language: data.language, strings: data.strings };
});

const keys = Object.keys(langs[0].strings);
for (const l of langs) {
  for (const k of keys) {
    if (typeof l.strings[k] !== 'string') throw new Error(`${l.file}: missing key ${k}`);
  }
  for (const k of Object.keys(l.strings)) {
    if (!keys.includes(k)) throw new Error(`${l.file}: unknown key ${k}`);
  }
}

const escape = text => {
  const bad = text.match(/"/);
  if (bad) throw new Error(`double quote in: ${text}`);
  const dollars = text.match(/\$(?![A-Za-z0-9_{])/g);
  if (dollars) throw new Error(`bare dollar sign in: ${text}`);
  return text.replace(/\n/g, '$\\r$\\n');
};

let out = '; Generated by tools/gen-lang.mjs from tools/lang/*.json - do not edit.\r\n\r\n';
for (const l of langs) {
  out += `; ${l.file}\r\n`;
  for (const k of keys) {
    out += `LangString ${k} \${${l.language}} "${escape(l.strings[k])}"\r\n`;
  }
  out += '\r\n';
}

fs.writeFileSync(outFile, '\uFEFF' + out, 'utf8');
console.log(`Wrote ${outFile}: ${langs.length} languages x ${keys.length} strings`);
